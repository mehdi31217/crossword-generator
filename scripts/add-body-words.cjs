for (const line of lines) {
  const idx = line.indexOf('|');
  if (idx === -1) continue;
  const word = line.substring(0, idx).trim();
  const clue = line.substring(idx + 1).trim();
  if (!word || !clue || latin.test(word) || word.includes(' ') || word.includes('_')) continue;
  if (!existing.has(word)) {
    dict.push({ word, clue, category: 'body', language: 'fa' });
    existing.add(word);
    added++;
  } else skipped++;
}
console.log('Added:', added, 'Skipped:', skipped);
fs.writeFileSync(DICT, JSON.stringify(dict, null, 2), 'utf-8');
console.log('Final body FA:', dict.filter(e => e.category === 'body' && e.language === 'fa').length);
