// Filter out words with spaces or underscores
const lines = RAW.split('\n').filter(l => l.trim());
let added = 0;
let skipped = 0;
for (const line of lines) {
  const idx = line.indexOf('|');
  if (idx === -1) continue;
  const w = line.substring(0, idx).trim();
  const c = line.substring(idx + 1).trim();
  if (!w || !c || latin.test(w) || w.includes(' ') || w.includes('_')) continue;
  if (!existing.has(w)) {
    dict.push({ word: w, clue: c, category: 'body', language: 'fa' });
    existing.add(w);
    added++;
  } else {
    skipped++;
  }
}

console.log('Added:', added, 'Skipped:', skipped);
fs.writeFileSync(DICT, JSON.stringify(dict, null, 2), 'utf-8');
