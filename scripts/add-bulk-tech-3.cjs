const lines = RAW.split('\n').filter(l => l.trim());
let added = 0;

for (const line of lines) {
  const idx = line.indexOf('|');
  if (idx === -1) continue;
  const word = line.substring(0, idx).trim();
  const clue = line.substring(idx + 1).trim();
  if (!word || !clue) continue;
  if (!existing.has(word)) {
    dict.push({ word, clue, category: 'tech', language: 'fa' });
    existing.add(word);
    added++;
  }
}

console.log('Added:', added);
fs.writeFileSync(DICT, JSON.stringify(dict, null, 2), 'utf-8');

