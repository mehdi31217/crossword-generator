let added = 0;
let skipped = 0;
for (const [cat, entries] of Object.entries(curated)) {
  for (const entry of entries) {
    const word = entry[0];
    const clue = entry[1];
    const n = normalize(word);
    
    if (n.length < 2 || n.length > 12) {
      skipped++;
      continue;
    }
    
    if (existingNorms.has(n)) {
      skipped++;
      continue;
    }
    
    existingNorms.add(n);
    maxId++;
    dict.push({
      id: String(maxId),
      word: word,
      clue: clue,
      category: cat,
      language: 'fa',
      length: n.length,
      created_at: new Date().toISOString()
    });
    added++;
  }
}

// Write updated dictionary.json
fs.writeFileSync(dictPath, JSON.stringify(dict, null, 2), 'utf8');
console.log(`Added ${added} words, skipped ${skipped} duplicates/short/long`);
console.log(`Total dictionary: ${dict.length} entries`);

