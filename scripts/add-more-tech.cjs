let added = 0;
for (const line of lines) {
  const idx = line.indexOf('|');
  if (idx === -1) continue;
  const word = line.substring(0, idx);
  const clue = line.substring(idx + 1);
  if (!existing.has(word)) {
    dict.push({ word, clue, category: 'tech', language: 'fa' });
    existing.add(word);
    added++;
  }
}
