#!/usr/bin/env node
const fs = require('fs');
const path = require('path');
const DICT = path.join(__dirname, '..', 'server', 'local-data', 'dictionary.json');
const dict = JSON.parse(fs.readFileSync(DICT, 'utf-8'));
const latin = /[a-zA-Z]/;
const targets = ['movies', 'nature', 'cities', 'knowledge', 'jobs', 'shahnameh'];

// Remove space/latin entries
let removed = 0;
for (let i = dict.length - 1; i >= 0; i--) {
  const e = dict[i];
  if (targets.includes(e.category) && e.language === 'fa' && (e.word.includes(' ') || latin.test(e.word))) {
    dict.splice(i, 1); removed++;
  }
}
console.log('Removed entries with space/Latin:', removed);
for (const cat of targets) {
  const cnt = dict.filter(e => e.category === cat && e.language === 'fa').length;
  console.log(`  ${cat}: ${cnt}`);
}

const existing = new Set(dict.map(e => e.word));
const catAdded = { movies: 0, nature: 0, cities: 0, knowledge: 0, jobs: 0, shahnameh: 0 };

function addRaw(raw, category) {
  const lines = raw.split('\n').filter(l => l.trim());
  for (const l of lines) {
    const i = l.indexOf('|'); if (i === -1) continue;
    const w = l.substring(0, i).trim(); const c = l.substring(i + 1).trim();
    if (!w || !c || w.includes(' ') || w.includes('_') || latin.test(w)) continue;
    if (!existing.has(w)) { dict.push({ word: w, clue: c, category, language: 'fa' }); existing.add(w); catAdded[category]++; }
  }
}

