for (const entry of dict) {
  if (entry.category === 'body' && entry.language === 'fa' && FIXES[entry.word]) {
    const old = entry.clue;
    entry.clue = FIXES[entry.word];
    if (old !== entry.clue) fixed++;
  }
}
console.log('Fixed clues:', fixed);

// Remove spaces and Latin entries
let removed = 0;
const cleaned = [];
for (const entry of dict) {
  if (entry.category === 'body' && entry.language === 'fa') {
    if (entry.word.includes(' ') || latin.test(entry.word)) {
      removed++;
      continue;
    }
  }
  cleaned.push(entry);
}
console.log('Removed space/latin:', removed);
dict.length = 0;
dict.push(...cleaned);

// Rebuild existing set
const existing = new Set(dict.map(e => e.word));

// Add new body words
const lines = RAW.split('\n').filter(l => l.trim() && !l.startsWith('//'));
let added = 0;
let skipped = 0;
for (const line of lines) {
  const idx = line.indexOf('|');
  if (idx === -1) continue;
  const word = line.substring(0, idx).trim();
  const clue = line.substring(idx + 1).trim();
  if (!word || !clue || latin.test(word) || word.includes(' ')) continue;
  if (!existing.has(word)) {
    dict.push({ word, clue, category: 'body', language: 'fa' });
    existing.add(word);
    added++;
  } else {
    skipped++;
  }
}
console.log('Added:', added, 'Skipped:', skipped);

fs.writeFileSync(DICT, JSON.stringify(dict, null, 2), 'utf-8');
