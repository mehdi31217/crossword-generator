def count_weak_clues(clues):
    bad_patterns = ['این را', 'این بود', 'در این', 'به این', 'از این', 'برای این', 'بدین', 'این کرد', 'این شد', 'این داشت', 'این داشتند', 'این کردند', 'این کرده']
    return sum(1 for c in clues if any(p in c for p in bad_patterns))

def fix_word_file(filepath):
    with open(filepath, 'r', encoding='utf-8') as f:
        content = f.read()
    
    # Find all word entries
    word_matches = list(re.finditer(r'word:\s*"([^"]*)"', content))
    total_fixed = 0
    name = os.path.basename(filepath)
    
    for wm in word_matches:
        word = wm[1]
        if word not in WORD_CLUES:
            continue
        
        new_clue = WORD_CLUES[word]
        
        # Find the specific clue for this word
        # We need to find the closest "clue:" after this word position
        pos = wm.end()
        clue_match = re.search(r'clue:\s*"([^"]*)"', content[pos:pos+500])
        if not clue_match:
            continue
        
        old_clue = clue_match.group(1)
        clue_start = pos + clue_match.start(1) - len('clue: "')
        clue_end = pos + clue_match.end(1)
        
        # Check if this clue is actually one of the vague ones
        bad_patterns = ['این را', 'این بود', 'در این', 'به این', 'از این', 'برای این', 'بدین', 'این کرد', 'این شد', 'این داشت', 'این داشتند', 'این کردند', 'این کرده']
        if not any(p in old_clue for p in bad_patterns):
            continue  # Skip already good clues
        
        # Check if the new clue is already in use nearby (avoid duplicates in same chapter)
        # Only replace if the old clue is indeed bad
        
        # Find the chapter block to check for duplicates
        # Get line number for context (just for display)
        line_num = content[:pos].count('\n') + 1
        
        content = content[:clue_start - 5] + f'clue: "{new_clue}"' + content[clue_end + 1:]
        total_fixed += 1
    
    with open(filepath, 'w', encoding='utf-8') as f:
        f.write(content)
    
    return total_fixed

