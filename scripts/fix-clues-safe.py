def fix_clues_safely(filepath):
    """Fix clues processing RIGHT to LEFT to avoid position corruption"""
    with open(filepath, 'r', encoding='utf-8') as f:
        content = f.read()
    
    # Find all word + clue pairs
    # Build list of (word, clue_start, clue_end, old_clue) from RIGHT to LEFT
    pairs = []
    for match in re.finditer(r'word:\s*"([^"]*)"\s*,\s*clue:\s*"([^"]*)"', content):
        word = match.group(1)
        clue_text = match.group(2)
        clue_start = match.start(2) - 1  # including the opening "
        clue_end = match.end(2)          # after the closing "
        pairs.append((word, clue_start, clue_end, clue_text))
    
    # Process RIGHT to LEFT
    bad_patterns = ['این را', 'این بود', 'در این', 'به این', 'از این', 'برای این', 'بدین', 'این کرد', 'این شد', 'این داشت', 'این داشتند', 'این کردند', 'این کرده']
    
    fixed = 0
    for word, clue_start, clue_end, old_clue in reversed(pairs):
        if any(p in old_clue for p in bad_patterns):
            if word in WORD_CLUES:
                new_clue = WORD_CLUES[word]
                # Replace just the clue portion
                content = content[:clue_start] + f'"{new_clue}"' + content[clue_end:]
                fixed += 1
    
    with open(filepath, 'w', encoding='utf-8') as f:
        f.write(content)
    
    return fixed

# Process all word files
files = sorted(f for f in os.listdir(WORD_DIR) if f.endswith('Words.ts') and f != 'shahnamehWords.ts')

total_fixed = 0
for fn in files:
    path = os.path.join(WORD_DIR, fn)
    fixed = fix_clues_safely(path)
    total_fixed += fixed
    
    # Count remaining weak clues
    with open(path) as f:
        clues = re.findall(r'clue:\s*"([^"]*)"', f.read())
    bad_patterns = ['این را', 'این بود', 'در این', 'به این', 'از این', 'برای این', 'بدین', 'این کرد', 'این شد', 'این داشت', 'این داشتند', 'این کردند', 'این کرده']
    remaining = sum(1 for c in clues if any(p in c for p in bad_patterns))
    print(f"{fn:35s}: fixed {fixed:3d}, remaining weak: {remaining:3d}/{len(clues):3d}")

print(f"\nTotal fixed: {total_fixed}")
