# Read existing data
with open(BOOKS_FILE, encoding='utf-8') as f:
    existing_books = json.load(f)
with open(CHAPTERS_FILE, encoding='utf-8') as f:
    existing_chapters = json.load(f)

existing_book_ids = {b['id'] for b in existing_books}
existing_chapter_keys = {(c['book_id'], c['chapter_index']) for c in existing_chapters}

added_books = 0
added_chapters = 0

for grade in GRADES:
    gid = grade['id']
    lessons = GRADE_LESSONS.get(gid, [])
    descs = GRADE_DESCS.get(gid, [])
    chapters_words = CHAPTER_WORDS.get(gid, [])

    if gid not in existing_book_ids:
        book = {
            'id': gid,
            'genre': 'education',
            'title': grade['title'],
            'author': 'کتاب فارسی',
            'description': f'کلمات و داستان‌های فارسی پایه {grade["title"]}',
            'cover_image': f'/images/school/{gid}.svg',
            'difficulty': grade['difficulty'],
        }
        existing_books.append(book)
        added_books += 1

    for i in range(min(len(lessons), len(descs), len(chapters_words), grade['chapters'])):
        ch_idx = i + 1
        key = (gid, ch_idx)
        if key in existing_chapter_keys:
            chapter = [c for c in existing_chapters if c['book_id'] == gid and c['chapter_index'] == ch_idx][0]
            # Update clues if they're generic
            needs_update = False
            for w in chapter.get('words', []):
                if 'کلمه‌ای از درس' in w.get('clue', ''):
                    needs_update = True
                    break
            if needs_update and i < len(chapters_words):
                word_pairs = chapters_words[i]
                chapter['words'] = [{'word': w, 'clue': c} for w, c in word_pairs]
                needs_update = True
            continue

        word_pairs = chapters_words[i]
        words = [{'word': w, 'clue': c} for w, c in word_pairs]

        chapter = {
            'id': str(uuid.uuid4()),
            'book_id': gid,
            'title': lessons[i],
            'description': descs[i],
            'image': f'/images/school/{gid}/ch{ch_idx}.svg',
            'chapter_index': ch_idx,
            'victory_text': f'آفرین! درس {lessons[i]} را با موفقیت به پایان رساندی! به یاد داشته باش که دانش بهترین دارایی است.',
            'words': words,
            'monster_avatar': f'/images/monsters/school/{gid}.svg',
        }
        existing_chapters.append(chapter)
        added_chapters += 1

# Write back
