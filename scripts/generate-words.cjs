/**
 * Comprehensive Persian crossword word generator v2.
 * Generates 1500+ words per category using aggressive compound word building.
 * Words are checked only against the same category's existing words.
 * Output: data/expandedGlueWords.ts with unique, category-relevant words.
 */
const fs = require('fs');
const path = require('path');

// ---- Load dictionary.json per category ----
const dict = JSON.parse(fs.readFileSync(
  path.join(__dirname, '..', 'server', 'local-data', 'dictionary.json'), 'utf8'
));

const normalize = (s) => {
  if (typeof s !== 'string') return '';
  return s.toUpperCase()
    .replace(/[\s\-]/g, '')
    .replace(/[آأإ]/g, 'ا')
    .replace(/[ئي]/g, 'ی')
    .replace(/ك/g, 'ک');
};

// ---- Load existing words per category ----
function getExistingWords(category) {
  const words = new Set();
  // From dictionary.json (same category only)
  for (const e of dict) {
    if (e.category === category && e.language === 'fa') {
      words.add(normalize(e.word));
    }
  }
  // From wordLists.ts (all FA words match by category name pattern)
  try {
    const wl = fs.readFileSync(path.join(__dirname, '..', 'data', 'wordLists.ts'), 'utf8');
    const re = /word:\s*['"]([^'"]+)['"]/g;
    let m;
    while ((m = re.exec(wl)) !== null) words.add(normalize(m[1]));
  } catch(e) {}
  // From glueWords.ts (same category glue)
  try {
    const gl = fs.readFileSync(path.join(__dirname, '..', 'data', 'glueWords.ts'), 'utf8');
    const ucat = category.toUpperCase();
    const re = new RegExp(`${ucat}_GLUE_FA[^;]*?word:\\s*['"]([^'"]+)['"]`, 'g');
    let m;
    while ((m = re.exec(gl)) !== null) words.add(normalize(m[1]));
  } catch(e) {}
  // Hash the category's own existing words
  const h = new Set();
  for (const w of words) {
    const n = normalize(w);
    if (n.length >= 2 && n.length <= 12) h.add(n);
  }
  return h;
}

