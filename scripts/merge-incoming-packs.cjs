#!/usr/bin/env node
/**
 * Merges hand-authored batches from data/wordPacks/incoming/ into the packs the
 * build pipeline reads, and turns the generic batch into a bundled TS array.
 *
 *   incoming/<cat>.glue.txt   → data/wordPacks/<cat>.glue.txt   (glue_dictionary.json)
 *   incoming/<cat>.words.txt  → data/wordPacks/<cat>.words.txt  (dictionary.json)
 *   incoming/common.glue.txt  → data/commonCrosswordGlue.ts     (MASSIVE_GLUE_FA)
 *
 * A line is dropped when its word already exists anywhere in the corpus, so the
 * merge is idempotent and re-runnable.
 *
 * Run: node scripts/merge-incoming-packs.cjs [--dry]
 */
const fs = require('fs');
const path = require('path');

const ROOT = path.resolve(__dirname, '..');
const IN = path.join(ROOT, 'data', 'wordPacks', 'incoming');
const PACKS = path.join(ROOT, 'data', 'wordPacks');
const DRY = process.argv.includes('--dry');
const ZW = new RegExp('\u200c', 'g');
const norm = (s) => s.toUpperCase().replace(ZW, '').replace(/[\s-]/g, '')
  .replace(/[آأإ]/g, 'ا').replace(/ئ/g, 'ی').replace(/ي/g, 'ی').replace(/ك/g, 'ک');

function corpusWords(includeIncoming) {
  const all = new Set();
  for (const f of ['server/local-data/dictionary.json', 'server/local-data/glue_dictionary.json']) {
    const p = path.join(ROOT, f);
    if (!fs.existsSync(p)) continue;
    for (const e of JSON.parse(fs.readFileSync(p, 'utf8'))) {
      if (e.language && e.language !== 'fa') continue;
      all.add(norm(e.word));
    }
  }
  for (const f of ['utils/glueWords.ts', 'data/glueWords.ts', 'data/glueWordsExtra.ts', 'data/wordLists.ts']) {
    const p = path.join(ROOT, f);
    if (!fs.existsSync(p)) continue;
    for (const m of fs.readFileSync(p, 'utf8').matchAll(/word:\s*["']([^"']+)["']/g)) all.add(norm(m[1]));
  }
  for (const dir of [PACKS, IN]) {
    if (!fs.existsSync(dir)) continue;
    if (dir === IN && !includeIncoming) continue;
    for (const f of fs.readdirSync(dir).filter((x) => x.endsWith('.txt'))) {
      for (const l of fs.readFileSync(path.join(dir, f), 'utf8').split(/\r?\n/)) {
        const at = l.indexOf('|');
        if (at > 0) all.add(norm(l.slice(0, at).trim()));
      }
    }
  }
  return all;
}

function readLines(file) {  if (!fs.existsSync(file)) return [];
  return fs.readFileSync(file, 'utf8').split(/\r?\n/)
    .map((l) => l.trim()).filter((l) => l && !l.startsWith('#') && !l.startsWith('//'))
    .map((l) => ({ word: l.slice(0, l.indexOf('|')).trim(), rest: l.slice(l.indexOf('|') + 1).trim() }))
    .filter((e) => e.word && e.rest);
}

// Base corpus excludes the drafts, otherwise a batch rejects itself. Sibling
// drafts are added per file so two batches cannot ship the same word.
const baseCorpus = corpusWords(false);
const draftWords = new Map();
for (const f of fs.readdirSync(IN).filter((x) => x.endsWith('.txt')).sort()) {
  draftWords.set(f, new Set(readLines(path.join(IN, f)).map((e) => norm(e.word))));
}
const report = [];

for (const f of fs.readdirSync(IN).filter((x) => x.endsWith('.txt')).sort()) {
  const taken = new Set(baseCorpus);
  for (const [other, words] of draftWords) if (other !== f) for (const w of words) taken.add(w);
  const src = path.join(IN, f);
  const entries = readLines(src);
  if (f === 'common.glue.txt') {
    report.push(`${f} → SKIPPED (data/commonCrosswordGlue.ts is generated by scripts/build-common-glue.cjs)`);
    continue;
  }
  const target = path.join(PACKS, f);
  const existingWords = new Set(readLines(target).map((e) => norm(e.word)));
  const fresh = entries.filter((e) => !taken.has(norm(e.word)) && !existingWords.has(norm(e.word)));
  report.push(`${f} → data/wordPacks/${f}: +${fresh.length} of ${entries.length}`);
  if (!DRY && fresh.length) {
    const prefix = fs.existsSync(target) && !fs.readFileSync(target, 'utf8').endsWith('\n') ? '\n' : '';
    fs.appendFileSync(target, prefix + fresh.map((e) => `${e.word}|${e.rest}`).join('\n') + '\n');
  }
  for (const e of fresh) baseCorpus.add(norm(e.word));
}

console.log(report.join('\n'));
console.log(DRY ? '\n(dry run — nothing written)' : '');
