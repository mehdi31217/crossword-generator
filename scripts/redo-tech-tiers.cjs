function addWords(list) {
  for (const [word, clue] of list) {
    if (!existing.has(word)) {
      dict.push({ word, clue, category: 'tech', language: 'fa' });
      existing.add(word);
      added++;
    } else {
      skipped++;
    }
  }
}

