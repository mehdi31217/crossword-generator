// === CHAPTERS ===

function addChapter(bookId, index, title, desc, victory, image, monster, words) {
  const nextId = chapters.length > 0 ? Math.max(...chapters.map(c => c.id)) + 1 : 1;
  chapters.push({
    id: nextId,
    book_id: bookId,
    chapter_order: index + 1,
    chapter_index: index,
    title,
    description: desc,
    image,
    victory_text: victory,
    monster_avatar: monster,
    words: words.map(w => ({ word: w.word, clue: w.clue })),
    created_at: new Date().toISOString()
  });
  console.log(`  Ch ${index + 1}: ${title}`);
}

