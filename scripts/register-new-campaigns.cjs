const fs = require('fs');
const path = require('path');

const BOOKS_FILE = path.join(__dirname, '..', 'server', 'local-data', 'story_books.json');
const CHAPTERS_FILE = path.join(__dirname, '..', 'server', 'local-data', 'story_chapters.json');

const books = JSON.parse(fs.readFileSync(BOOKS_FILE, 'utf8'));
const chapters = JSON.parse(fs.readFileSync(CHAPTERS_FILE, 'utf8'));

// === BOOKS ===

function addBook(id, genre, title, author, desc, cover, difficulty, style) {
  if (books.find(b => b.id === id)) {
    console.log(`Book "${id}" already exists, skipping.`);
    return;
  }
  books.push({
    id,
    genre,
    title,
    author,
    description: desc,
    cover_image: cover,
    difficulty,
    style,
    required_stars: 0,
    created_at: new Date().toISOString()
  });
  console.log(`Added book: ${title}`);
}

